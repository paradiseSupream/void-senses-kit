import { createServerFn } from "@tanstack/react-start";

import type { EventFilters, MonetizationStats } from "@/lib/analytics-agg";
import type { WeeklyReport } from "@/lib/weekly-report.types";

const SELECT =
  "event_type,slot,variant,session_id,tool_slug,revenue_cents,device,utm_source,created_at,format,zone,is_vip,duration_ms,metric_value,country,ip_hash,suspect,click_id";

export type StatsInput = {
  token: string;
  days?: number;
  country?: string;
  device?: string;
  format?: string;
  slot?: string;
  audience?: "all" | "vip" | "free";
  excludeSuspect?: boolean;
};

export type StatsResult = {
  stats: MonetizationStats;
  /** Unfiltered option lists so the dashboard filters never go empty. */
  options: { countries: string[]; devices: string[]; formats: string[]; slots: string[] };
  generatedAt: string;
};

function normalize(input: StatsInput): Required<Omit<StatsInput, "token">> & { token: string } {
  return {
    token: String(input?.token ?? ""),
    days: Math.max(1, Math.min(90, Number(input?.days ?? 7))),
    country: String(input?.country ?? ""),
    device: String(input?.device ?? ""),
    format: String(input?.format ?? ""),
    slot: String(input?.slot ?? ""),
    audience: (input?.audience ?? "all") as "all" | "vip" | "free",
    excludeSuspect: input?.excludeSuspect !== false,
  };
}

export const getMonetizationStats = createServerFn({ method: "POST" })
  .inputValidator(normalize)
  .handler(async ({ data }): Promise<StatsResult> => {
    const { aggregate, filterRows } = await import("@/lib/analytics-agg");
    const { requireAdmin, admin } = await import("@/lib/admin-core.server");

    const legacy = process.env["ANALYTICS_ADMIN_TOKEN"];
    if (!legacy || data.token !== legacy) await requireAdmin(data.token);

    const db = admin();
    const since = new Date(Date.now() - data.days * 86_400_000).toISOString();
    const { data: rows, error } = await db
      .from("ad_events")
      .select(SELECT)
      .gte("created_at", since)
      .order("created_at", { ascending: false })
      .limit(50000);
    if (error) throw new Error(error.message);

    const list = (rows ?? []) as never[];
    const filters: EventFilters = {
      country: data.country || undefined,
      device: data.device || undefined,
      format: data.format || undefined,
      slot: data.slot || undefined,
      audience: data.audience,
      excludeSuspect: data.excludeSuspect,
    };

    const uniq = (pick: (row: Record<string, unknown>) => unknown) =>
      [
        ...new Set(
          (list as unknown as Array<Record<string, unknown>>)
            .map((r) => String(pick(r) ?? ""))
            .filter(Boolean),
        ),
      ].sort();

    return {
      stats: aggregate(filterRows(list, filters), data.days),
      options: {
        countries: uniq((r) => r["country"]),
        devices: uniq((r) => r["device"]),
        formats: uniq((r) => r["format"] ?? r["slot"]),
        slots: uniq((r) => r["slot"]),
      },
      generatedAt: new Date().toISOString(),
    };
  });

/** Weekly performance reports (auto-generated by the cron endpoint). */
export const adminWeeklyReports = createServerFn({ method: "POST" })
  .inputValidator((input: { token: string; generate?: boolean }) => ({
    token: String(input?.token ?? ""),
    generate: input?.generate === true,
  }))
  .handler(async ({ data }): Promise<WeeklyReport[]> => {
    const { requireAdmin, readSettings } = await import("@/lib/admin-core.server");
    const { generateWeeklyReport, listWeeklyReports } = await import(
      "@/lib/weekly-report.server"
    );
    const legacy = process.env["ANALYTICS_ADMIN_TOKEN"];
    if (!legacy || data.token !== legacy) await requireAdmin(data.token);
    if (data.generate) {
      const { ads } = await readSettings();
      await generateWeeklyReport(ads.rpm_estimate_cents);
    }
    return listWeeklyReports();
  });
